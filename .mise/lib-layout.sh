# shellcheck shell=bash
# shellcheck disable=SC2016 # backticks and $variables in single quotes are literal Markdown and yq
# Helpers for layout:lint and layout:format. Source after lib.sh, from the
# repository root. Everything is read from git's tracked file list and from
# contracts/layout/layout.yaml, so an untracked file never counts.
#
#   tracked tree ----+
#                    +--> layout_render_block --> layout:format writes it
#   layout.yaml -----+                             between the README markers
#                                                          |
#   README block <----- layout_current_block ---- layout:lint compares
#
# A directory under packages/ has one of three kinds, detected from the
# tracked tree: flux-package (package.yaml), render-module (module/ and no
# package.yaml) or manifest-only (neither, with a top-level YAML manifest).

readonly layout_data=contracts/layout/layout.yaml
readonly layout_readme=README.md
readonly layout_begin_prefix='<!-- layout:begin'
readonly layout_begin='<!-- layout:begin: generated by mise run layout:format from contracts/layout/layout.yaml; do not edit by hand -->'
readonly layout_end='<!-- layout:end -->'

# Prints the tracked top-level directories, one per line, sorted.
layout_tracked_folders() {
  git ls-files | awk -F/ 'NF > 1 {print $1}' | LC_ALL=C sort -u
}

# Prints the folders layout.yaml declares, one per line, sorted.
layout_declared_folders() {
  yq -r '.folders | keys | .[]' "$layout_data" | LC_ALL=C sort
}

# Prints the directories directly under packages/ that hold tracked files,
# one per line, sorted. A file directly under packages/ is not a package.
layout_package_dirs() {
  git ls-files -- packages | awk -F/ 'NF > 2 {print $2}' | LC_ALL=C sort -u
}

# Prints the kind of one package directory, or "unclassifiable".
layout_package_kind() {
  local name="$1" file has_package=0 has_module=0 has_manifest=0
  while IFS= read -r file; do
    case "${file#"packages/$name/"}" in
    package.yaml) has_package=1 ;;
    module/*) has_module=1 ;;
    */*) ;;
    *.yaml) has_manifest=1 ;;
    esac
  done < <(git ls-files -- "packages/$name")
  if ((has_package && has_module)); then
    printf 'unclassifiable\n'
  elif ((has_package)); then
    printf 'flux-package\n'
  elif ((has_module)); then
    printf 'render-module\n'
  elif ((has_manifest)); then
    printf 'manifest-only\n'
  else
    printf 'unclassifiable\n'
  fi
}

# Succeeds when git tracks the path or anything under it.
layout_is_tracked() {
  [[ -n "$(git ls-files -- "$1")" ]]
}

# Prints the README block: the folders, the package kinds and packages, and
# the places to look for common tasks. Deterministic: sorted, no dates.
layout_render_block() {
  local name kind
  printf '\n**Folders**\n\n| Folder | Holds |\n| --- | --- |\n'
  yq -r '.folders | to_entries | sort_by(.key) | .[] | "| `" + .key + "/` | " + .value.holds + " |"' "$layout_data"
  yq -r '"| (top-level files) | " + .top_level_files.holds + " |"' "$layout_data"
  printf '\n**Packages**\n\n'
  yq -r '.package_kinds | to_entries | .[] | "- `" + .key + "`: " + .value.holds' "$layout_data"
  printf '\n| Package | Kind | README |\n| --- | --- | --- |\n'
  while IFS= read -r name; do
    kind=$(layout_package_kind "$name")
    if layout_is_tracked "packages/$name/README.md"; then
      printf '| `%s` | `%s` | [packages/%s/README.md](packages/%s/README.md) |\n' "$name" "$kind" "$name" "$name"
    else
      printf '| `%s` | `%s` | missing |\n' "$name" "$kind"
    fi
  done < <(layout_package_dirs)
  printf '\n**Where do I...**\n\n| Task | Path |\n| --- | --- |\n'
  yq -r '.find[] | "| " + .question + " | `" + .path + "` |"' "$layout_data"
  printf '\n'
}

# Prints why the markers in a file are unusable, or nothing when there is
# exactly one begin line before exactly one end line.
layout_marker_problem() {
  local file="$1" begins ends first_begin first_end
  begins=$(grep -c -F -- "$layout_begin_prefix" "$file" || true)
  ends=$(grep -c -x -F -- "$layout_end" "$file" || true)
  if ((begins != 1 || ends != 1)); then
    printf '%s has %s begin marker(s) and %s end marker(s); it needs exactly one of each (%s ... %s)\n' "$file" "$begins" "$ends" "$layout_begin_prefix" "$layout_end"
    return 0
  fi
  first_begin=$(grep -n -F -- "$layout_begin_prefix" "$file" | head -1 | cut -d: -f1)
  first_end=$(grep -n -x -F -- "$layout_end" "$file" | head -1 | cut -d: -f1)
  if ((first_begin >= first_end)); then
    printf '%s has its end marker before its begin marker\n' "$file"
  fi
}

# Prints the lines between the markers of a file, exclusive.
layout_current_block() {
  awk -v begin="$layout_begin_prefix" -v end="$layout_end" '
    $0 == end {inside = 0}
    inside {print}
    index($0, begin) == 1 {inside = 1}
  ' "$1"
}

# Replaces the lines between the markers of a file with the contents of a
# second file, and writes nothing else.
layout_replace_block() {
  local file="$1" block="$2" temporary
  temporary=$(mktemp "${TMPDIR:-/tmp}/layout-readme.XXXXXX")
  awk -v block="$block" -v begin="$layout_begin_prefix" -v begin_line="$layout_begin" -v end="$layout_end" '
    index($0, begin) == 1 {
      print begin_line
      while ((getline line < block) > 0) print line
      skip = 1
      next
    }
    $0 == end {skip = 0}
    !skip {print}
  ' "$file" >"$temporary"
  cat -- "$temporary" >"$file"
  rm -f -- "$temporary"
}

# Prints one line per way the layout and the tree disagree; prints nothing
# when they agree. Reads only; never writes.
layout_problems() {
  local folder reference name kind path expected actual
  if [[ ! -f "$layout_data" ]]; then
    printf '%s is missing\n' "$layout_data"
    return 0
  fi
  if ! yq -e '.folders' "$layout_data" >/dev/null 2>&1; then
    printf '%s is not readable YAML with a folders map\n' "$layout_data"
    return 0
  fi
  while IFS= read -r folder; do
    printf 'the tracked folder %s/ is not in %s\n' "$folder" "$layout_data"
  done < <(comm -23 <(layout_tracked_folders) <(layout_declared_folders))
  while IFS= read -r folder; do
    printf '%s lists %s, which is not a tracked folder\n' "$layout_data" "$folder"
  done < <(comm -13 <(layout_tracked_folders) <(layout_declared_folders))
  while read -r folder reference; do
    [[ -n "$folder" ]] || continue
    if ! layout_declared_folders | grep -qx -F -- "$reference"; then
      printf '%s: folders.%s.may_reference names %s, which is not a folder\n' "$layout_data" "$folder" "$reference"
    fi
  done < <(yq -r '.folders | to_entries | .[] | .key as $folder | .value.may_reference[] | $folder + " " + .' "$layout_data")
  while IFS= read -r path; do
    layout_is_tracked "$path" || printf '%s: the find path %s is not in the tracked tree\n' "$layout_data" "$path"
  done < <(yq -r '.find[].path' "$layout_data")
  while IFS= read -r name; do
    kind=$(layout_package_kind "$name")
    [[ "$kind" != unclassifiable ]] ||
      printf 'packages/%s fits no kind: it needs package.yaml, or module/ without package.yaml, or a top-level YAML manifest, and not both package.yaml and module/\n' "$name"
    layout_is_tracked "packages/$name/README.md" || printf 'packages/%s has no tracked README.md\n' "$name"
  done < <(layout_package_dirs)
  if [[ ! -f "$layout_readme" ]]; then
    printf '%s is missing\n' "$layout_readme"
    return 0
  fi
  actual=$(layout_marker_problem "$layout_readme")
  if [[ -n "$actual" ]]; then
    printf '%s\n' "$actual"
    return 0
  fi
  expected=$(layout_render_block)
  actual=$(layout_current_block "$layout_readme")
  if [[ "$expected" != "$actual" ]]; then
    printf '%s: the block between the markers is not the render of %s; run mise run layout:format. First difference:\n' "$layout_readme" "$layout_data"
    diff <(printf '%s\n' "$actual") <(printf '%s\n' "$expected") | head -10 | sed 's/^/  /' || true
  fi
}
