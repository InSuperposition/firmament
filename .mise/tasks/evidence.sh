#!/usr/bin/env bash
#MISE description="Render the evidence page for the cv tenant from a run record of the tour, labeled observed, and a snapshot of configured state, labeled configured; the page shows only allowlisted facts, escaped"
#USAGE flag "--record <file>" help="The run record to show (default: the newest complete record of the environment, else the newest)"
#USAGE flag "--snapshot <file>" help="Use this snapshot of configured state instead of collecting one from the cluster; only allowlisted fields are kept"
#USAGE flag "--out <directory>" help="Where to write index.html (default: evidence/page in the environment's state folder)"
set -euo pipefail
# shellcheck source=../lib.sh
source "${MISE_PROJECT_ROOT:?}/.mise/lib.sh"
cd "$MISE_PROJECT_ROOT"

readonly schema=contracts/run-record/schema.cue
# shellcheck disable=SC2154 # mise sets usage_* from the #USAGE spec
record_file="${usage_record:-}"
snapshot_file="${usage_snapshot:-}"
out_directory="${usage_out:-}"

# The state folder holds the records the tour wrote; offline use needs none.
state_directory="${TF_VAR_state_directory:-}"

# Prints the newest record of the state folder, a complete one first.
newest_record() {
  local file complete_file="" any_file=""
  [[ -d "$state_directory/evidence" ]] || return 0
  # shellcheck disable=SC2012 # newest first; the names are generated by the tour
  while IFS= read -r file; do
    [[ -n "$any_file" ]] || any_file="$file"
    if [[ -z "$complete_file" && "$(jq -r .complete "$file")" == true ]]; then
      complete_file="$file"
    fi
  done < <(ls -t "$state_directory"/evidence/record-*.json 2>/dev/null)
  printf '%s\n' "${complete_file:-$any_file}"
}

[[ -n "$record_file" ]] || record_file=$(newest_record)
[[ -n "$record_file" && -f "$record_file" ]] ||
  fail "no run record to show; run the tour first with: mise run tour (or pass --record <file>)" || exit
cue vet -c -d '#Contract' "$schema" "$record_file" ||
  fail "$record_file does not match contracts/run-record" || exit
complete=$(jq -r .complete "$record_file")

# Keeps only the allowlisted fields of a snapshot; anything else, such as an
# address or a pod name, is dropped here and so can never reach the page.
snapshot_allowlist='{
  collected: (.collected // ""),
  image: {configured: (.image.configured // ""), running: (.image.running // "")},
  chart: {digest: (.chart.digest // ""), signer_pattern: (.chart.signer_pattern // "")},
  flux: {status: (.flux.status // "unavailable"), kustomizations: [(.flux.kustomizations // [])[] | {name: (.name // ""), ready: (.ready // false)}]},
  hubble: {status: (.hubble.status // "unavailable"), window: (.hubble.window // ""), counts: [(.hubble.counts // [])[] | {source_namespace: (.source_namespace // ""), verdict: (.verdict // ""), count: (.count // 0)}]},
  policies: {status: (.policies.status // "unavailable"), names: [(.policies.names // [])[] | tostring]}
}'

# Collects the snapshot from the cluster and the repository. A source that
# fails is marked unavailable, which is not the same as empty.
collect_snapshot() {
  local kubeconfig flux flux_status="ok" hubble hubble_status="ok" policies policies_status="ok" running
  kubeconfig=$(environment_kubeconfig) || return
  flux=$(kubectl --kubeconfig "$kubeconfig" -n flux-system get kustomizations.kustomize.toolkit.fluxcd.io -o json 2>/dev/null |
    jq -c '[.items[] | {name: .metadata.name, ready: (any(.status.conditions[]?; .type == "Ready" and .status == "True"))}]') || {
    flux='[]'
    flux_status=unavailable
  }
  running=$(kubectl --kubeconfig "$kubeconfig" -n cv get pods -o json 2>/dev/null |
    jq -r '[.items[0].status.containerStatuses[0].imageID // ""] | .[0] | sub("^.*@"; "")') || running=""
  hubble=$(kubectl --kubeconfig "$kubeconfig" -n kube-system exec ds/cilium -c cilium-agent -- \
    hubble observe --to-namespace cv --last 200 -o jsonpb 2>/dev/null |
    jq -sc '[.[].flow | {source_namespace: (.source.namespace // "host or world"), verdict}] | group_by([.source_namespace, .verdict]) | map(.[0] + {count: length})') || {
    hubble='[]'
    hubble_status=unavailable
  }
  [[ "$hubble_status" != ok || "$hubble" != '[]' ]] || hubble_status=empty
  policies=$(kubectl --kubeconfig "$kubeconfig" get imagevalidatingpolicies.policies.kyverno.io,validatingpolicies.policies.kyverno.io -o json 2>/dev/null |
    jq -c '[.items[].metadata.name]') || {
    policies='[]'
    policies_status=unavailable
  }
  jq -n --arg collected "$(date -u +%Y-%m-%dT%H:%M:%SZ)" \
    --arg configured "$(yq -r '.image.digest' clusters/singularity/values/cv.yaml)" --arg running "$running" \
    --arg chart "$(yq -r '.pin.digest' packages/cv/package.yaml)" --arg signer "$(yq -r '.verify.identity' packages/cv/package.yaml)" \
    --argjson flux "$flux" --arg flux_status "$flux_status" --argjson hubble "$hubble" --arg hubble_status "$hubble_status" \
    --argjson policies "$policies" --arg policies_status "$policies_status" \
    '{collected: $collected, image: {configured: $configured, running: $running}, chart: {digest: $chart, signer_pattern: $signer},
      flux: {status: $flux_status, kustomizations: $flux}, hubble: {status: $hubble_status, window: "the last 200 flows into cv", counts: $hubble},
      policies: {status: $policies_status, names: $policies}}'
}

if [[ -n "$snapshot_file" ]]; then
  [[ -f "$snapshot_file" ]] || fail "no snapshot at $snapshot_file" || exit
  snapshot=$(jq -c "$snapshot_allowlist" "$snapshot_file") || exit
else
  snapshot=$(collect_snapshot | jq -c "$snapshot_allowlist") || exit
fi

record_sha=$(shasum -a 256 "$record_file" | cut -d' ' -f1)

# The page: static, no script, every value escaped.
# shellcheck disable=SC2016 # the jq program names jq variables, not shell ones
page_program='
def e: tostring | @html;
def yes($b): if $b then "yes" else "no" end;
def observation:
  if .kind == "flow" then "\(.verdict | e) flow, \(.count | e) in \(.window_seconds | e) s"
  elif .kind == "http" then "HTTP \(.status | e)"
  else (.line | e) end;
def action_row:
  "<tr><td>\(.guarantee | e)</td><td>\(.started | e)</td><td>\(.finished | e)</td><td><code>\(.command | e)</code></td>"
  + "<td>\(if .reference then "\(.reference.kind | e) \(.reference.value | e)" else "" end)</td>"
  + "<td>\([.controls[] | "\(.name | e): \(yes(.passed))"] | join("<br>"))</td>"
  + "<td>\([.observations[] | observation] | join("<br>"))</td></tr>";
def section_state($s; $empty):
  if $s == "unavailable" then "<p><strong>Unavailable:</strong> this source could not be read, which is not the same as nothing to report.</p>"
  elif $s == "empty" then "<p>\($empty | e)</p>" else "" end;
"<!doctype html>
<html lang=\"en\">
<head>
<meta charset=\"utf-8\">
<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">
<title>How the cv site is run</title>
<style>
body{font:16px/1.5 system-ui,sans-serif;max-width:60rem;margin:0 auto;padding:1rem;color:#1a1a1a;background:#fff}
table{border-collapse:collapse;width:100%}th,td{border:1px solid #767676;padding:.4rem;text-align:left;vertical-align:top}
code{word-break:break-word}.badge{padding:.1rem .5rem;border:2px solid #1a1a1a;font-weight:bold}
@media (prefers-color-scheme:dark){body{color:#eee;background:#111}th,td{border-color:#999}.badge{border-color:#eee}}
</style>
</head>
<body>
<h1>How the cv site is run</h1>
<p>Run record: <span class=\"badge\">\(if $record.complete then "complete" else "incomplete" end)</span>, started \($record.started | e), finished \($record.finished // "" | e).
The cluster ran revision \($record.revision.cluster | e); the checkout was at \($record.revision.checkout | e) (\(if $record.revision.matches then "the same" else "not the same" end)).</p>
<h2>Observed</h2>
<p>What the tour saw, from the run record.</p>
<table>
<tr><th>Guarantee</th><th>Started</th><th>Finished</th><th>Command</th><th>Tested</th><th>Controls</th><th>Observed</th></tr>
\([$record.actions[] | action_row] | join("\n"))
</table>
<h2>Configured</h2>
<p>What the repository and the cluster say now, collected \($snapshot.collected | e). This is not what the tour observed.</p>
<ul>
<li>cv image in the repository: \($snapshot.image.configured | e); running: \($snapshot.image.running | e)</li>
<li>cv chart digest in the repository: \($snapshot.chart.digest | e)</li>
<li>Signer pattern the chart must match (configured): <code>\($snapshot.chart.signer_pattern | e)</code></li>
</ul>
<h3>Flux Kustomizations</h3>
\(section_state($snapshot.flux.status; "No Kustomization was found."))
<ul>\([$snapshot.flux.kustomizations[] | "<li>\(.name | e): \(if .ready then "Ready" else "not Ready" end)</li>"] | join(""))</ul>
<h3>Network flows into cv</h3>
\(section_state($snapshot.hubble.status; "No flows in the window: \($snapshot.hubble.window)."))
<ul>\([$snapshot.hubble.counts[] | "<li>from \(.source_namespace | e): \(.verdict | e) x \(.count | e)</li>"] | join(""))</ul>
<h3>Admission policies</h3>
\(section_state($snapshot.policies.status; "No admission policy was found."))
<ul>\([$snapshot.policies.names[] | "<li>\(. | e)</li>"] | join(""))</ul>
<h2>Verify</h2>
<p>The record on this page has sha256 \($sha | e). Nothing on this page proves that the commands ran or that the clock was right; it shows what the tour wrote down.</p>
<p>Check the digest yourself: <code>shasum -a 256 &lt;the record file&gt;</code>.</p>
</body>
</html>"'

[[ -n "$out_directory" ]] || out_directory="${state_directory:?run this through mise, or pass --out}/evidence/page"
mkdir -p "$out_directory"
jq -rn --slurpfile record_input "$record_file" --argjson snapshot "$snapshot" --arg sha "$record_sha" \
  '($record_input[0]) as $record | '"$page_program" >"$out_directory/index.html"
printf 'Wrote %s (%s record)\n' "$out_directory/index.html" "$([[ "$complete" == true ]] && echo complete || echo incomplete)"
